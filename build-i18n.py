    missing = []
    for code in LOCALES:
        for key in EN:
            if key not in i18n[code] or not i18n[code][key]:
                missing.append(f"{code}:{key}")
    if missing:
        raise SystemExit("missing " + ", ".join(missing[:20]))

    def js_str(value):
        return "'" + str(value).replace("\\", "\\\\").replace("'", "\\'") + "'"

    def emit_map(mapping, indent=2):
        pad = " " * indent
        lines = ["{"]
        items = list(mapping.items())
        for i, (key, val) in enumerate(items):
            comma = "," if i < len(items) - 1 else ""
            if isinstance(val, dict):
                lines.append(f"{pad}{js_str(key)}: {emit_map(val, indent + 2)}{comma}")
            else:
                lines.append(f"{pad}{js_str(key)}: {js_str(val)}{comma}")
        lines.append((" " * (indent - 2)) + "}")
        return "\n".join(lines)

    locales = "[" + ", ".join(js_str(code) for code in LOCALES) + "]"
